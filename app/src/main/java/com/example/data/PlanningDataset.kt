    fun getSummary(zone: String): PlanningSummary {
        val filtered = when (zone) {
            "Khu B" -> items.firstOrNull { it.stt == "I" }
            "Khu C" -> items.firstOrNull { it.stt == "II" }
            else -> items.firstOrNull { it.name.startsWith("Tổng") }
        }
        return PlanningSummary(
            zoneName = zone,
            totalLandArea = filtered?.landArea ?: 0.0,
            maxBuildArea = filtered?.maxBuildArea ?: 0.0,
            buildingDensity = filtered?.buildingDensity ?: 0.0,
            far = filtered?.far ?: 0.0,
            maxFloorArea = filtered?.maxFloorArea ?: 0.0,
            totalUnits = filtered?.unitsCount ?: 0,
            tourists = filtered?.touristCapacity ?: 0
        )
    }
